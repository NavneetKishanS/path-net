import { spawn } from 'node:child_process'
import { writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import pg from 'pg'
import { initializeAccountStorage } from './account-migration.mjs'

const defaultWebDir = resolve(dirname(fileURLToPath(import.meta.url)), '..')

function runDocker(args, { cwd, env, capture = false }) {
  return new Promise((resolveCommand, reject) => {
    const child = spawn('docker', args, { cwd, env, shell: false, stdio: capture ? ['ignore', 'pipe', 'pipe'] : 'inherit' })
    let output = ''
    if (capture) {
      child.stdout.on('data', (chunk) => { output += chunk })
      // Compose's resolved configuration can contain credentials; never log it.
      child.stderr.resume()
    }
    child.on('error', () => reject(new Error('Local accounts need Docker with Compose. Install and start Docker Desktop, or configure an existing account database.')))
    child.on('close', (code) => code === 0 ? resolveCommand(output) : reject(new Error('Local database startup failed. Check that Docker is running and the selected local ports are available.')))
  })
}

function publishedPort(config, service, target) {
  const port = config.services?.[service]?.ports?.find((item) => Number(item.target) === target)
  const value = Number(port?.published)
  if (!Number.isInteger(value) || value < 1 || value > 65535) {
    throw new Error(`The ${service} service needs a fixed local port in docker-compose.yml.`)
  }
  if (!['127.0.0.1', '::1'].includes(port.host_ip)) {
    throw new Error(`The ${service} service must bind to a loopback address for automatic local accounts.`)
  }
  return { port: value, host: port.host_ip === '::1' ? '[::1]' : '127.0.0.1' }
}

export function localAccountEnvironment(config) {
  const database = config.services?.db?.environment ?? {}
  const db = publishedPort(config, 'db', 5432)
  const api = publishedPort(config, 'api', 3000)
  const web = publishedPort(config, 'web', 5173)
  const name = database.POSTGRES_DB
  const password = database.POSTGRES_PASSWORD
  if (!name || !password) throw new Error('The local database service needs POSTGRES_DB and POSTGRES_PASSWORD.')
  return {
    PATHNET_ACCOUNT_DATABASE_URL: `postgresql://${encodeURIComponent(database.POSTGRES_USER || 'postgres')}:${encodeURIComponent(password)}@${db.host}:${db.port}/${encodeURIComponent(name)}?sslmode=disable`,
    PATHNET_ACCOUNT_LOCAL: 'true',
    NEXT_PUBLIC_ACCOUNT_PROXY: 'true',
    NEXT_PUBLIC_DATA_SOURCE: 'rest',
    NEXT_PUBLIC_API_URL: `http://${api.host}:${api.port}`,
    PORT: String(web.port),
  }
}

async function initialize(connectionString) {
  const client = new pg.Client({ connectionString, connectionTimeoutMillis: 10000 })
  try {
    await client.connect()
    return await initializeAccountStorage(client)
  } catch {
    throw new Error('Account database initialization failed. Check the configured connection and apply the graph migrations and seed first. Existing accounts have been retained.')
  } finally {
    await client.end().catch(() => undefined)
  }
}

/** Provision only the repository's local stack; explicit database connections remain operator-owned. */
export async function prepareLocalAccounts({
  webDir = defaultWebDir,
  env = process.env,
  explicitDatabase = false,
  run = runDocker,
  initializeStorage = initialize,
  log = console.log,
} = {}) {
  if (env.PATHNET_ACCOUNT_BOOTSTRAP === 'false') return { mode: 'disabled' }
  const configured = env.PATHNET_ACCOUNT_DATABASE_URL?.trim()
  const managed = env.PATHNET_ACCOUNT_LOCAL === 'true' && !explicitDatabase
  if (configured && !managed) {
    const result = await initializeStorage(configured)
    log('Account storage is ready; existing accounts and profiles are retained.')
    return { mode: 'configured', ...result }
  }

  const options = { cwd: resolve(webDir, '..'), env }
  log('Preparing the local database and account storage...')
  const rawConfig = await run(['compose', 'config', '--format', 'json'], { ...options, capture: true })
  let config
  try { config = JSON.parse(rawConfig) } catch { throw new Error('Docker Compose did not return a valid local configuration.') }
  const defaults = localAccountEnvironment(config)
  // Compose waits for the healthy database and the completed migration/seed service.
  await run(['compose', 'up', '-d', 'db', 'api'], options)
  const result = await initializeStorage(defaults.PATHNET_ACCOUNT_DATABASE_URL)

  const content = '# Generated by npm run dev for the persistent local Docker database.\n'
    + '# Set PATHNET_ACCOUNT_LOCAL=false to manage a different database yourself.\n'
    + Object.entries(defaults).filter(([key]) => key !== 'PORT').map(([key, value]) => `${key}=${JSON.stringify(value)}`).join('\n') + '\n'
  try {
    await writeFile(resolve(webDir, '.env.local'), content, { flag: 'wx', mode: 0o600 })
    log('Created the ignored web/.env.local configuration.')
  } catch (error) {
    if (error.code !== 'EEXIST') throw error
    log('Existing web/.env.local retained; local database settings are applied to this process.')
  }
  // A host dev server follows Compose's web port unless the operator supplied PORT.
  Object.assign(env, { ...defaults, ...(env.PORT ? { PORT: env.PORT } : {}) })
  log('Local accounts are ready. Database data is retained between starts.')
  return { mode: 'local', ...result }
}
